"""Write docs/reports/model_survey.md from models/descriptors/*.yaml.  Usage: PYTHONPATH=sw python3 -m npumodel.report"""
import glob
import os
import sys
from collections import Counter

from . import schema as S


def main():
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    ds = [S.load(p) for p in sorted(glob.glob(os.path.join(root, "models", "descriptors", "*.yaml")))]
    for d in ds:
        S.validate(d)
    mx_w = max(abs(d["derived"]["weight_check_ratio"] - 1) for d in ds) * 100
    mx_t = max(abs(d["derived"].get("published_total_ratio", 1) - 1) for d in ds) * 100
    L = ["# Model survey (Phase 1, step 1)", "",
         "Generated by `python3 -m npumodel.report` from `models/descriptors/*.yaml`. Do not edit by hand.",
         "Configs are snapshots of the Hugging Face `config.json` files in `models/configs/`; `models/repos.tsv` lists the repositories. "
         "What was verified beyond config.json, and how, is in `docs/reports/model_features.md`.", "",
         "## Size and structure", "",
         "| Model | Layers | Hidden | Params (B) | Published (B) | Active (B) | Experts (top-k) | Attention mix | Weights GB | Check |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for d in ds:
        dv, pub = d["derived"], d.get("published")
        mix = Counter()
        for a, _ in S.expand_layers(d):
            mix[a["kind"] + (f"/{a['variant']}" if a.get("variant") else "") + ("+window" if a.get("window") else "")
                + ("+sparse" if a.get("sparse") else "")] += 1
        moes = [f for f in d["ffn_types"].values() if f["kind"] == "moe"]
        ex = f"{moes[0]['n_experts']} (top-{moes[0]['top_k']})" if moes else "-"
        act = f"{dv['params_active_b']:.1f}" + (f" ({dv['params_active_prefill_b']:.1f} prefill)" if "params_active_prefill_b" in dv else "")
        L.append(f"| {d['name']} | {d['dims']['n_layers']} | {d['dims']['hidden']} | {dv['params_total_b']:.0f} | "
                 f"{pub['total_b'] if pub else '-'} / {pub['active_b'] if pub else '-'} active | {act} | {ex} | "
                 f"{', '.join(f'{k} x{v}' for k, v in mix.items())} | {dv['published_weight_gb']:.0f} | {dv['weight_check_ratio']:.3f} |")
    L += ["", "Two independent checks on the layer plans. `Check` = weight bytes estimated from the layer plan and dtypes divided by the published "
          f"safetensors size (worst case {mx_w:.0f}% off). `Published` = total / active parameter counts quoted by the model authors "
          f"(totals within {mx_t:.0f}%; the authors round, and 'active' conventions for embeddings differ).", "",
          "## Weight dtypes as published", "", "| Model | Expert | Dense | Note |", "|---|---|---|---|"]
    for d in ds:
        dt = d["weights"]["dtypes"]
        L.append(f"| {d['name']} | {dt['expert']} | {dt['dense']} | {d['weights']['notes']} |")
    L += ["", "## KV cache and recurrent state per sequence", "",
          "FP8 unless a layer type says otherwise (DeepSeek: NVFP4 global KV, MXFP4 index keys; Mistral: FP8). `Global` grows with context; "
          "`window + state` is constant per sequence (sliding windows, recurrent state).", "",
          "| Model | Global + index, B/token | 128K | 1M | Window + state (const) |", "|---|---|---|---|---|"]
    for d in ds:
        b = {c: S.kv_breakdown(d, c) for c in (131072, 1048576)}
        gi = lambda c: b[c]["global"] + b[c]["index"]
        L.append(f"| {d['name']} | {gi(1048576) / 1048576:,.0f} | {gi(131072) / 2**30:.2f} GB | {gi(1048576) / 2**30:.1f} GB | "
                 f"{(b[1048576]['window'] + b[1048576]['state']) / 2**20:.0f} MB |")
    L += ["", "## Hyper-connections and hashed-gather tables (hardware requirements)", "",
          "Per token and per sublayer (two sublayers per layer). `Mixer MACs` = the mixing projection; `% of active MACs` is that over all layers relative to the model's active "
          "parameters (one MAC per active weight per token).", "",
          "| Model | Variant | Streams | Mixer weights (M) | Mixer MACs / sublayer | Residual stream traffic / sublayer | % of active MACs | Gather rows / token | Row bytes |",
          "|---|---|---|---|---|---|---|---|---|"]
    for d in ds:
        hc = d.get("extras", {}).get("hyper_connections")
        tabs = d.get("extras", {}).get("tables", [])
        if not (hc or tabs):
            continue
        h = d["dims"]["hidden"]
        n_sub = 2 * (d["dims"]["n_layers"] + ((d.get("mtp") or {}).get("n_layers") or 0))
        if hc:
            o = S.hc_ops(hc, h)
            tot = (o["macs_proj"] + o["macs_elem"]) * n_sub
            pct = f"{100 * tot / (d['derived']['params_active_b'] * 1e9):.1f}%"
            hcs = (hc["variant"], hc["mult"], f"{S.hc_params_per_sublayer(hc, h) / 1e6:.2f}", f"{o['macs_proj'] / 1e6:.2f} M", f"{o['stream_bytes'] / 1024:.0f} KB", pct)
        else:
            hcs = ("-", "-", "-", "-", "-", "-")
        rows = sum(t["lookups_per_token"] for t in tabs)
        rb = ", ".join(f"{t['dim'] * S.DTYPE_BYTES[d['weights']['dtypes']['table']]:.0f} B x {t['lookups_per_token']}" for t in tabs) or "-"
        L.append(f"| {d['name']} | " + " | ".join(str(x) for x in hcs) + f" | {rows or '-'} | {rb} |")
    L += ["", "## Speculative decoding", "",
          "| Model | In main weights (MTP) | Separate drafter |", "|---|---|---|"]
    for d in ds:
        m, dr = d.get("mtp"), d.get("drafter")
        ms = f"{m['n_layers']} x ({m['attn']}, {m['ffn']})" if m else "-"
        drs = (f"{dr['kind']}: {dr['n_layers']} layers, block {dr.get('block')}" + (f", window {dr['window']}" if dr.get("window") else "")) if dr else "-"
        L.append(f"| {d['name']} | {ms} | {drs} |")
    L += ["", "## Features outside the base schema", "",
          "`required` = outside the base schema but the hardware and compiler will support it (decision recorded in `docs/spec/hyper_connections.md`). "
          "`warn` = modeled approximately, inferred, or not yet decided. `info` = recorded only.", ""]
    for sev in ("required", "warn"):
        L += [f"### {sev}", "", "| Model | Feature | Detail |", "|---|---|---|"]
        for d in ds:
            for f in d["flags"]:
                if f["severity"] == sev:
                    L.append(f"| {d['name']} | `{f['id']}` | {f['detail']} |")
        L.append("")
    L += ["### info", ""]
    for d in ds:
        ids = ", ".join(f"`{f['id']}`" for f in d["flags"] if f["severity"] == "info")
        L.append(f"- **{d['name']}**: {ids}")
    out = os.path.join(root, "docs", "reports", "model_survey.md")
    open(out, "w").write("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    sys.exit(main())
