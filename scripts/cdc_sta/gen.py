#!/usr/bin/env python3
"""Write the ORFS inputs for one afifo configuration.

Usage: gen.py <name> <kind: top|blk> <WIDTH> <DEPTH> <afifo.sv> <outdir>

top: afifo inside a harness (afifo_top) with a registered producer in wr_clk and a consumer register q in rd_clk,
     flattened by ORFS (the instance is u_f). blk: afifo itself as the ORFS top.
Writes <outdir>/<name>.mk, <name>.sdc (the two clocks only) and, for top, <name>_top.sv.
"""
import sys

name, kind, w, d, src, out = sys.argv[1:7]
w, d = int(w), int(d)
files = [src]
if kind == 'top':
    top = f'{out}/{name}_top.sv'
    open(top, 'w').write(f'''// generated by scripts/cdc_sta/gen.py: afifo WIDTH {w} DEPTH {d} with a producer and a consumer register
module afifo_top (
  input  logic wr_clk, wr_rst_n, rd_clk, rd_rst_n,
  input  logic wr_valid_i, rd_ready_i,
  input  logic [{w}-1:0] wr_data_i,
  output logic wr_ready_o, rd_valid_o,
  output logic [{w}-1:0] q
);
  logic wr_valid, wr_ready, rd_valid;
  logic [{w}-1:0] wr_data, rd_data;
  always_ff @(posedge wr_clk) begin wr_valid <= wr_valid_i; wr_data <= wr_data_i; wr_ready_o <= wr_ready; end
  always_ff @(posedge rd_clk) begin rd_valid_o <= rd_valid; if (rd_valid && rd_ready_i) q <= rd_data; end
  afifo #(.WIDTH({w}), .DEPTH({d})) u_f (
    .wr_clk, .wr_rst_n, .wr_valid, .wr_ready, .wr_data,
    .rd_clk, .rd_rst_n, .rd_valid, .rd_ready(rd_ready_i), .rd_data);
endmodule
''')
    files.append(top)
    design = 'afifo_top'
    params = ''
else:
    design = 'afifo'
    params = f'export VERILOG_TOP_PARAMS = WIDTH {w} DEPTH {d}\n'
open(f'{out}/{name}.sdc', 'w').write('create_clock -name wr_clk -period 667 [get_ports wr_clk]\n'
                                     'create_clock -name rd_clk -period 833 [get_ports rd_clk]\n')
open(f'{out}/{name}.mk', 'w').write(f'''export DESIGN_NAME = {design}
export DESIGN_NICKNAME = cdc_{name}
export PLATFORM = asap7
export VERILOG_FILES = {' '.join(files)}
export SDC_FILE = {out}/{name}.sdc
{params}export CORE_UTILIZATION ?= 40
export SYNTH_REPEATABLE_BUILD ?= 1
export SYNTH_HIERARCHICAL = 0
''')
