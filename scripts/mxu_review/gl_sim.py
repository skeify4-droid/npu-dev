#!/usr/bin/env python3
"""Implementability review: does Yosys read the MXU RTL as Icarus does? Gate-level run of the review suite.

Yosys synthesizes `mxu` (mxu.sv, mxu_dec.sv, mxu_wpack.sv, mxu_array.sv) flat to generic gates at the testbench's parameters, with
`mxu_pe` kept as a blackbox (the PE arithmetic stays RTL in the simulation: a 0.4 M-cell flat PE array would make Icarus too slow).
Because the original mxu_array loses its PE instances when mxu_pe is a blackbox (finding I-2), the netlist is made from the packed copy
build/mxu_review/fix/mxu_array.sv (fix_array_packed.sh proves it equivalent to the original). The netlist module is renamed
`mxu_gl`; a wrapper `mxu` with the RTL's parameter and port list instantiates it, so tb_mxu_rev.sv (compiled with -DGATE) and the
oracle comparison of run_review.py are unchanged. Everything else Yosys does to mxu.sv, mxu_dec.sv, mxu_wpack.sv and the array's
control (procs, memories, FSM recoding, async resets, the swp0 / swp1 mixed drivers) is in the netlist.
Usage: gl_sim.py [--dim 8 16] [--fuzz N] [--xfill] [--only SUBSTR] [--modes ...] [--stalls ...]
"""
import argparse
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import run_review as RR  # noqa: E402

ROOT = RR.ROOT
GL = os.path.join(RR.BUILD, 'gl')


def netlist(dim):
    d = os.path.join(GL, str(dim))
    if os.path.isdir(d):
        shutil.rmtree(d)
    core = os.path.join(d, 'rtl', 'core')
    os.makedirs(core)
    shutil.copytree(os.path.join(ROOT, 'rtl', 'arith'), os.path.join(d, 'rtl', 'arith'))
    fix = os.path.join(RR.BUILD, 'fix', 'mxu_array.sv')
    if not os.path.exists(fix):
        sys.exit('run scripts/mxu_review/fix_array_packed.sh first (needs %s)' % fix)
    net = os.path.join(core, 'mxu_net.sv')
    params = 'DIM %d SPM_LAT 2 ACC_LAT %d ACC_ROWS %d SPM_BYTES %d' % (dim, RR.ACC_LAT, RR.ACC_ROWS[dim], RR.SPM_BYTES)
    sets = ' '.join('-set %s %s' % (k, v) for k, v in zip(params.split()[0::2], params.split()[1::2]))
    script = ('read_verilog -sv -lib rtl/arith/mxu_pe.sv; read_verilog -sv isa/gen/isa_pkg.sv rtl/core/mxu.sv rtl/core/mxu_dec.sv '
              'rtl/core/mxu_wpack.sv %s; chparam %s mxu; hierarchy -check -auto-top; synth -flatten; '
              'tee -q -o %s/stat.txt stat; rename -top mxu_gl; write_verilog -noattr %s' % (fix, sets, d, net))
    r = subprocess.run(['yosys', '-q', '-l', os.path.join(d, 'yosys.log'), '-p', script], cwd=ROOT, capture_output=True, text=True)
    if r.returncode:
        sys.exit('yosys failed:\n' + r.stdout[-2000:] + r.stderr[-2000:])
    # wrapper: the RTL header of mxu (parameters and ports), body = the netlist
    src = open(os.path.join(ROOT, 'rtl', 'core', 'mxu.sv')).read()
    m = re.search(r'module mxu #\((.*?)\n\) \((.*?)\n\);', src, re.S)
    assert m
    wrap = ('// generated by scripts/mxu_review/gl_sim.py: the RTL interface of mxu around the Yosys netlist mxu_gl\n'
            'module mxu #(%s\n) (%s\n);\n  mxu_gl u_gl (.*);\nendmodule\n' % (m.group(1), m.group(2)))
    open(os.path.join(core, 'mxu_wrap.sv'), 'w').write(wrap)
    cells = re.search(r'^\s+(\d+) cells', open(os.path.join(d, 'stat.txt')).read(), re.M)
    print('DIM %d: netlist %s (%s cells besides the PEs)' % (dim, net, cells.group(1) if cells else '?'))
    sys.stdout.flush()
    return d


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dim', type=int, nargs='+', default=[8])
    ap.add_argument('--fuzz', type=int, default=10)
    ap.add_argument('--only', default='')
    ap.add_argument('--xfill', action='store_true')
    ap.add_argument('--modes', nargs='+', default=['serial', 'pipe'])
    ap.add_argument('--stalls', type=int, nargs='+', default=[0, 30])
    args = ap.parse_args()
    nrun = nfail = 0
    for dim in args.dim:
        vvp = RR.build(dim, rtl_root=netlist(dim), tag='gl', defines=('GATE',))
        for p in RR.cases(dim, args.fuzz):
            if args.only and args.only not in p.name:
                continue
            for mode in args.modes:
                for stall in args.stalls:
                    nrun += 1
                    errs, d = RR.run_case(vvp, p, mode, stall, seed=nrun, sub='gl_cases', xfill=int(args.xfill))
                    tag = 'GL DIM %2d %-22s %-6s stall %2d (%d ins)' % (dim, p.name, mode, stall, len(p.ins))
                    if errs:
                        nfail += 1
                        print('FAIL', tag, '->', d)
                        for e in errs[:8]:
                            print('   ', e)
                    else:
                        print('ok  ', tag)
                    sys.stdout.flush()
    print('%d runs, %d failed' % (nrun, nfail))
    return 1 if nfail else 0


if __name__ == '__main__':
    sys.exit(main())
