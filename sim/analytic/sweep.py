"""Phase 1 step 4 sweeps. Writes docs/reports/phase1_sweeps.md, docs/spec/plots/*.svg and build/phase1/*.csv.

    PYTHONPATH=sw:sim python -m analytic.sweep            (make sweep)

Serving point used to fix the package count per model (docs/spec/arch.md):
  context 128K, 64 concurrent sequences per replica, >= 50 tokens/s per user WITHOUT speculative decoding,
  weights deployed as `fp8` (every class at min(published dtype, FP8); 4-bit QAT experts stay 4-bit).
"""
import csv
import glob
import os

from npumodel import opgraph as G, schema as S
from . import hw as HW, roofline as R, svgplot as P

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PLOTS = os.path.join(ROOT, "docs", "spec", "plots")
CSV = os.path.join(ROOT, "build", "phase1")
REPORT = os.path.join(ROOT, "docs", "reports", "phase1_sweeps.md")
SERVE = dict(batch=64, ctx=131072, min_user=50.0)
PKGS = (1, 2, 4, 8, 16, 32)
GROUPS = [("up to 450 B", ["qwen3_8_flash_next", "mimo_v2_6_flash", "glm_5_3_flash", "minimax_m3_1_flash"]),
          ("550 to 800 B", ["ling_3_1_flash", "step_5_preview", "glm_5_3", "deepseek_v4_1_flash"]),
          ("over 800 B", ["muse_spark_open", "mimo_v2_6_pro", "mistral_large_4"])]


def load_all():
    return {os.path.basename(p)[:-5]: S.load(p) for p in sorted(glob.glob(os.path.join(ROOT, "models", "descriptors", "*.yaml")))}


def deploy_dtype(desc, mode):
    """Weight dtypes for a deployment mode: published | fp8 | mxfp4 (experts MXFP4, rest as fp8)."""
    if mode == "published":
        return None
    cap = lambda d: d if S.DTYPE_BYTES[d] <= 1.0 + 1 / 16 else "fp8"
    w = {k: cap(v) for k, v in desc["weights"]["dtypes"].items() if k not in ("embed", "hc")}
    if mode == "mxfp4":
        w["expert"] = "mxfp4" if S.DTYPE_BYTES[w["expert"]] > 0.6 else w["expert"]
    return w


def max_gamma(desc):
    """Longest draft the model's own drafter was trained for: the DSpark / DFlash block, or 3 chained MTP steps
    (an MTP module reused beyond its depth, as serving stacks do; acceptance beyond 3 is not modeled)."""
    sd = desc.get("spec_decode") or {}
    if not sd:
        return 0
    return max(sd["draft_tokens"], 3) if sd["method"] == "mtp" else sd["draft_tokens"]


def serving_packages(desc, hw, mode="fp8", **sp):
    sp = dict(SERVE, **sp)
    wd = deploy_dtype(desc, mode)
    for n in PKGS:
        r = R.best_decode(desc, hw, n, sp["batch"], sp["ctx"], weight_dtype=wd)
        if r and r["tok_s_user"] >= sp["min_user"]:
            return n, r
    return None, None


def write_csv(name, rows):
    os.makedirs(CSV, exist_ok=True)
    with open(os.path.join(CSV, name), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def md_table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    os.makedirs(PLOTS, exist_ok=True)
    M = load_all()
    hw = HW.make()
    pk = HW.peaks(hw)
    opb = HW.ops_per_byte(hw)
    rep = ["# Phase 1 sweeps (generated by `make sweep`; do not edit)", "",
           f"Baseline die: {pk['peak_fp8'] / 1e15:.2f} PFLOPS FP8 peak, {pk['peak_hbm_bw'] / 1e12:.2f} TB/s HBM peak, "
           f"{pk['hbm_bytes'] / 1e9:.0f} GB; roofline uses MXU efficiency {hw['mxu_eff']} and HBM efficiency {hw['hbm_eff']} "
           f"-> sustained ops:byte {opb:.0f}. Serving point: {SERVE['batch']} sequences x {SERVE['ctx'] // 1024}K context, "
           f">= {SERVE['min_user']:.0f} tokens/s per user, no speculative decoding, `fp8` deployment. Raw data: `build/phase1/*.csv`.", ""]

    # ---- 1. MoE crossover: tokens per expert where the expert GEMM turns compute-bound
    rows, mx = [], []
    for dt in ("fp8", "nvfp4", "mxfp4", "bf16"):
        b = S.DTYPE_BYTES[dt]
        rate = pk["bf16"] if dt == "bf16" else pk["fp8"]
        mstar = rate * b / (2 * pk["hbm_bw"])
        pts = [(m, min(1.0, (2 * m / b) / (rate / pk["hbm_bw"]))) for m in (1, 2, 4, 8, 16, 32, 64, 128, 256, 512, 1024, 2048)]
        if dt != "bf16":   # bf16 (2 B at half the MXU rate) has exactly the fp8 curve; named in the fp8 series
            mx.append(("fp8 (same as bf16)" if dt == "fp8" else dt, pts))
        rows.append({"dtype": dt, "bytes_per_weight": round(b, 4), "crossover_tokens_per_expert": round(mstar, 1)})
    write_csv("moe_crossover.csv", rows)
    P.line_chart(os.path.join(PLOTS, "moe_crossover.svg"), mx, "Routed-expert GEMM: MXU utilization vs tokens per expert",
                 "tokens per expert per step", "fraction of sustained MXU rate", xlog=True, ylim=(0, 1.05))
    cross = {r["dtype"]: r["crossover_tokens_per_expert"] for r in rows}
    mrows = []
    for slug, d in M.items():
        f = next((f for f in d["ffn_types"].values() if f["kind"] == "moe"), None)
        wd = deploy_dtype(d, "fp8") or d["weights"]["dtypes"]
        dt = wd["expert"] if wd["expert"] in cross else "fp8"
        m = cross[dt]
        mrows.append([d["name"], f["n_experts"], f["top_k"], dt, m, int(m * f["n_experts"] / f["top_k"])])
    rep += ["## 1. When do MoE layers become compute-bound?", "",
            "Expert GEMM intensity is 2 x tokens-per-expert FLOPs per weight byte, so the crossover is "
            "`tokens/expert = sustained ops:byte x bytes per weight / 2` (BF16 also halves the MXU rate).", "",
            md_table(["weights", "bytes/weight", "tokens per expert at crossover"],
                     [[r["dtype"], r["bytes_per_weight"], r["crossover_tokens_per_expert"]] for r in rows]), "",
            "Tokens in flight per EP group (decode batch x draft tokens) needed for every expert to reach the crossover "
            "under uniform routing, at the `fp8` deployment:", "",
            md_table(["model", "experts", "top-k", "expert dtype", "tokens/expert", "tokens per step"], mrows), "",
            "![MoE crossover](../spec/plots/moe_crossover.svg)", ""]

    # ---- 2. decode bandwidth floor per model (batch 1, 8K context, weights-only minimum packages)
    frows, fl = [], []
    for slug, d in M.items():
        wd = deploy_dtype(d, "fp8")
        n, pp, tp = R.min_packages(d, hw, 1, 8192, weight_dtype=wd)
        r = R.best_decode(d, hw, n, 1, 8192, weight_dtype=wd, objective="tok_s_user")
        t = G.totals(G.build(d, "decode", 1, 8192, weight_dtype=wd))
        frows.append({"model": d["name"], "packages": n, "weight_GB_per_token": round(t["w_bytes"] / 1e9, 2),
                      "kv_MB_per_token_8K": round(t["kv_bytes"] / 1e6, 1), "step_ms": round(r["step_s"] * 1e3, 2),
                      "tok_s_user": round(r["tok_s_user"], 1), "pp": r["pp"], "tp": r["tp"]})
    write_csv("decode_floor.csv", frows)
    rep += ["## 2. Decode bandwidth floor (batch 1, 8K context, fewest packages that hold the weights)", "",
            "Bytes read per decoded token and the resulting single-user speed. At batch 1 every op is HBM-bound, so this is "
            "the floor the weights alone impose.", "",
            md_table(["model", "packages", "weight GB / token", "KV MB / token", "step (ms)", "tokens/s/user", "PP", "TP"],
                     [list(r.values()) for r in frows]), ""]

    # ---- 3. minimum package count at the serving point, and the frontier per model
    srows, front = [], {}
    for slug, d in M.items():
        wd = deploy_dtype(d, "fp8")
        n0 = R.min_packages(d, hw, 1, 8192, weight_dtype=wd)[0]
        nk = R.min_packages(d, hw, SERVE["batch"], SERVE["ctx"], weight_dtype=wd)
        ns, r = serving_packages(d, hw)
        n1m = R.min_packages(d, hw, 8, 1 << 20, weight_dtype=wd)
        kvseq = S.kv_bytes(d, SERVE["ctx"]) / 1e9
        srows.append({"model": d["name"], "weights_only": n0, "kv_fits": nk[0], "serving": ns,
                      "tok_s_user": round(r["tok_s_user"], 1) if r else "-", "tok_s_per_pkg": round(r["tok_s_total"] / ns) if r else "-",
                      "mapping": f"PP{r['pp']} TP{r['tp']}" if r else "-", "kv_GB_per_seq_128K": round(kvseq, 2),
                      "pkgs_8x1M": n1m[0] if n1m else "-"})
        pts = []
        for b in (1, 4, 16, 64, 256, 1024):
            rr = R.best_decode(d, hw, ns or 32, b, SERVE["ctx"], weight_dtype=wd)
            if rr:
                pts.append((rr["tok_s_user"], rr["tok_s_total"] / (ns or 32), b))
        front[slug] = pts
    write_csv("serving_packages.csv", srows)
    rows_fr = [{"model": M[s]["name"], "batch": b, "tok_s_user": round(u, 1), "tok_s_per_pkg": round(t)} for s, p in front.items() for u, t, b in p]
    write_csv("frontier_128k.csv", rows_fr)
    rep += ["## 3. Package count per model", "",
            "`weights_only`: fewest packages that hold the weights (batch 1, 8K). `kv_fits`: also the KV of 64 x 128K. "
            f"`serving`: fewest packages that also reach {SERVE['min_user']:.0f} tokens/s/user at 64 x 128K (best PP/TP mapping). "
            "`8x1M`: fewest packages that hold 8 sequences of 1M tokens.", "",
            md_table(["model", "weights only", "KV fits", "serving", "tokens/s/user", "tokens/s per package", "mapping",
                      "KV GB / seq @128K", "8 x 1M"], [list(r.values()) for r in srows]), ""]
    for gi, (gname, slugs) in enumerate(GROUPS):
        ser = [(M[s]["name"], [(u, t) for u, t, b in front[s]]) for s in slugs]
        fn = f"frontier_{gi}.svg"
        P.line_chart(os.path.join(PLOTS, fn), ser, f"Decode at 128K context on the serving package count ({gname})",
                     "tokens/s per user", "tokens/s per package", xlog=True, ylog=True, vlines=[(SERVE["min_user"], "50 tok/s/user")])
        rep += [f"![frontier {gname}](../spec/plots/{fn})", ""]
    rep += ["Points are batch 1, 4, 16, 64, 256, 1024; larger batches are further left (lower speed per user, higher throughput). "
            "A curve stops where the KV no longer fits.", ""]

    # ---- 4. sensitivity: stacks per die, dies per package, weight dtype, context
    sens = []
    for slug, d in M.items():
        base_n, base = serving_packages(d, hw)
        if not base:
            continue
        row = {"model": d["name"], "pkgs": base_n, "base_tok_s_pkg": round(base["tok_s_total"] / base_n)}
        for st in (5, 6):
            h2 = HW.make(stacks=st)
            n2, r2 = serving_packages(d, h2)
            row[f"stacks{st}"] = f"{n2} pkg, x{(r2['tok_s_total'] / n2) / (base['tok_s_total'] / base_n):.2f}" if r2 else "-"
        for dpp in (1, 4):
            h3 = HW.make(dies_per_pkg=dpp)
            n3, r3 = serving_packages(d, h3)
            row[f"dies{dpp}"] = f"{n3 * dpp} dies, x{(r3['tok_s_total'] / (n3 * dpp)) / (base['tok_s_total'] / (2 * base_n)):.2f}/die" if r3 else "-"
        n4, r4 = serving_packages(d, hw, mode="mxfp4")
        row["mxfp4_experts"] = f"{n4} pkg, x{(r4['tok_s_total'] / n4) / (base['tok_s_total'] / base_n):.2f}" if r4 else "-"
        sens.append(row)
    write_csv("sensitivity.csv", sens)
    rep += ["## 4. Sensitivity at the serving point", "",
            "Each cell: package (or die) count that meets the serving point, and throughput per package (per die for the "
            "dies-per-package columns) relative to the baseline (4 stacks/die, 2 dies/package, `fp8`).", "",
            md_table(["model", "pkgs", "tokens/s/pkg", "5 stacks/die", "6 stacks/die", "1 die/pkg", "4 dies/pkg", "MXFP4 experts"],
                     [list(r.values()) for r in sens]), ""]
    ctxs = (8192, 32768, 131072, 262144, 524288, 1048576)
    crow = []
    for gi, (gname, slugs) in enumerate(GROUPS[:1]):
        ser = []
        for s in slugs:
            d = M[s]
            n = next(r["serving"] for r in srows if r["model"] == d["name"]) or 32
            pts = []
            for c in ctxs:
                rr = R.best_decode(d, hw, n, 16, c, weight_dtype=deploy_dtype(d, "fp8"))
                if rr:
                    pts.append((c, rr["tok_s_user"]))
                    crow.append({"model": d["name"], "packages": n, "ctx": c, "tok_s_user": round(rr["tok_s_user"], 1)})
            ser.append((d["name"], pts))
        P.line_chart(os.path.join(PLOTS, "context.svg"), ser, "Decode speed vs context, batch 16 (models up to 450 B)",
                     "context (tokens)", "tokens/s per user", xlog=True)
    write_csv("context.csv", crow)
    rep += ["![context](../spec/plots/context.svg)", "",
            md_table(["model", "packages", "context", "tokens/s/user"], [list(r.values()) for r in crow]), ""]

    # ---- 5. speculative decoding: per-user speed-up vs draft length with each model's own drafter
    srows2, ser = [], []
    pick = ["minimax_m3_1_flash", "mimo_v2_6_flash", "deepseek_v4_1_flash", "mistral_large_4", "glm_5_3_flash"]
    for s in pick:
        d = M[s]
        n = next(r["serving"] for r in srows if r["model"] == d["name"]) or 32
        wd = deploy_dtype(d, "fp8")
        r0 = R.best_decode(d, hw, n, 16, SERVE["ctx"], weight_dtype=wd, objective="tok_s_user")
        pts = []
        for g in range(0, max_gamma(d) + 1):
            r = R.best_decode(d, hw, n, 16, SERVE["ctx"], weight_dtype=wd, gamma=g, domain="code", objective="tok_s_user")
            if r:
                pts.append((g, r["tok_s_user"] / r0["tok_s_user"]))
                srows2.append({"model": d["name"], "method": d["spec_decode"]["method"], "gamma": g, "tau": round(r["tau"], 2),
                               "tok_s_user": round(r["tok_s_user"], 1), "speedup": round(r["tok_s_user"] / r0["tok_s_user"], 2)})
        ser.append((f"{d['name']} ({d['spec_decode']['method']})", pts))
    write_csv("specdec.csv", srows2)
    P.line_chart(os.path.join(PLOTS, "specdec.svg"), ser, "Speculative decoding, code domain, batch 16, 128K",
                 "draft tokens per round (up to the trained block)", "per-user speed-up vs no drafting", hlines=[(1.0, "no drafting")])
    best = {}
    for r in srows2:
        if r["model"] not in best or r["speedup"] > best[r["model"]]["speedup"]:
            best[r["model"]] = r
    rep += ["## 5. Speculative decoding", "",
            "Acceptance from `npumodel.specdec` (DSpark paper Table 1, Qwen3-8B, code domain); drafter cost from the op graph "
            "(drafter layers, the target LM head over the draft positions, the Markov head). Verification runs gamma + 1 tokens "
            "per sequence through the target.", "",
            md_table(["model", "method", "best gamma", "tau", "tokens/s/user", "speed-up"],
                     [[r["model"], r["method"], r["gamma"], r["tau"], r["tok_s_user"], r["speedup"]] for r in best.values()]), "",
            "![spec decode](../spec/plots/specdec.svg)", ""]

    # ---- 6. where decode time goes at the serving point
    krows = []
    for slug, d in M.items():
        n = next(r["serving"] for r in srows if r["model"] == d["name"]) or 32
        r = R.best_decode(d, hw, n, SERVE["batch"], SERVE["ctx"], weight_dtype=deploy_dtype(d, "fp8"))
        if not r:
            continue
        bk = r["breakdown"]["by_kind"]
        tot = sum(bk.values()) + r["breakdown"]["comm"]
        g = lambda *ks: f"{100 * sum(bk.get(k, 0) for k in ks) / tot:.0f}%"
        krows.append([d["name"], n, g("gemm", "lm_head"), g("moe_experts"), g("attn"), g("index_scan", "topk"), g("linear_scan"),
                      f"{100 * r['breakdown']['comm'] / tot:.0f}%", f"{100 * r['breakdown']['memory'] / max(1e-12, r['breakdown']['memory'] + r['breakdown']['compute']):.0f}%"])
    rep += ["## 6. Where decode time goes (serving point)", "",
            md_table(["model", "pkgs", "dense GEMM + LM head", "routed experts", "attention", "index scan + top-k", "linear attn",
                      "communication", "HBM-bound share of op time"], krows), ""]
    with open(REPORT, "w") as f:
        f.write("\n".join(rep) + "\n")
    print("\n".join(rep))


if __name__ == "__main__":
    main()
